"""
Write frontend/src/foodWords.ts from chat/words.py and chat/phrase_languages.py.

The cover site needs the same words, case forms and filler words as the
server, in every language: it shows a phrase in her language and turns what
she types back into the Serbian words before sending. This command is the one
place that file comes from, and a test fails when the committed file is out
of date.

    uv run python manage.py export_food_words
"""

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from chat.phrase_languages import ENDINGS, FILLERS, LANGUAGE_WORDS, stems_for

FRONTEND_FILE = Path(settings.BASE_DIR).parent / "frontend" / "src" / "foodWords.ts"


def _js(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_frontend_module() -> str:
    languages = list(LANGUAGE_WORDS)
    words = {lang: list(LANGUAGE_WORDS[lang]) for lang in languages}
    stems = {lang: [list(stems_for(lang, w)) for w in LANGUAGE_WORDS[lang]] for lang in languages}
    endings = {lang: list(ENDINGS[lang]) for lang in languages}
    fillers = {lang: sorted(FILLERS[lang]) for lang in languages}
    return f"""// GENERATED by `uv run python manage.py export_food_words` (backend).
// Source of truth: backend/chat/words.py and backend/chat/phrase_languages.py.
// Do not edit by hand; a backend test fails if this file is out of date.
//
// Resume-phrase words in every language, aligned by position with Serbian.
// She sees and types the phrase in her language; the site sends the Serbian
// words. Not secret: the strength comes from 105^4 phrases plus rate limits.

export type PhraseLanguage = {" | ".join(_js(lang) for lang in languages)};

const LANGUAGES: readonly PhraseLanguage[] = {_js(languages)};

const WORDS: Readonly<Record<PhraseLanguage, readonly string[]>> = {_js(words)};

const STEMS: Readonly<Record<PhraseLanguage, readonly (readonly string[])[]>> = {_js(stems)};

const ENDINGS: Readonly<Record<PhraseLanguage, readonly string[]>> = {_js(endings)};

const FILLERS: Readonly<Record<PhraseLanguage, readonly string[]>> = {_js(fillers)};

/** Lowercase, đ -> dj, strip diacritics (č -> c, ë -> e). Same as the server's fold(). */
export function fold(text: string): string {{
  return text.toLowerCase().replaceAll("đ", "dj").normalize("NFD").replace(/\\p{{M}}/gu, "");
}}

function buildForms(lang: PhraseLanguage): Map<string, number> {{
  const forms = new Map<string, number>();
  WORDS[lang].forEach((word, index) => forms.set(fold(word), index));
  STEMS[lang].forEach((stems, index) => {{
    for (const stem of stems) {{
      for (const ending of ENDINGS[lang]) {{
        if (!forms.has(stem + ending)) forms.set(stem + ending, index);
      }}
    }}
  }});
  return forms;
}}

const FORMS = new Map(LANGUAGES.map((lang) => [lang, buildForms(lang)] as const));

/** Every accepted form per language -> word position. Exposed for the parity test. */
export function formsOf(lang: PhraseLanguage): ReadonlyMap<string, number> {{
  return FORMS.get(lang) ?? new Map();
}}

function wordsOf(text: string): string[] {{
  return fold(text).split(/[^\\p{{L}}]+/u).filter(Boolean);
}}

function matchIn(lang: PhraseLanguage, words: string[]): string[] | null {{
  const fillers = new Set(FILLERS[lang]);
  const kept = words.filter((w) => !fillers.has(w));
  if (kept.length !== 4) return null;
  const forms = formsOf(lang);
  const serbian: string[] = [];
  for (const word of kept) {{
    const index = forms.get(word);
    const sr = index === undefined ? undefined : WORDS.sr[index];
    if (sr === undefined) return null;
    serbian.push(sr);
  }}
  return serbian;
}}

/**
 * The Serbian words for a typed phrase, or null if it is not a phrase.
 * Tries her current language first, then every other language, so a phrase
 * started in one language still works after switching.
 */
export function phraseFromInput(text: string, preferred: PhraseLanguage): string[] | null {{
  const words = wordsOf(text);
  for (const lang of [preferred, ...LANGUAGES.filter((l) => l !== preferred)]) {{
    const match = matchIn(lang, words);
    if (match) return match;
  }}
  return null;
}}

/**
 * Could this be a phrase, even a mistyped or partial one? Then it must never
 * be written back onto the page. Judged on all typed words, fillers included.
 */
export function mightBePhrase(text: string): boolean {{
  const words = wordsOf(text);
  return words.length >= 3 || words.some((w) => LANGUAGES.some((l) => formsOf(l).has(w)));
}}

/** Show a Serbian phrase from the server ("krofna-kora-musaka-maslac") in her language. */
export function displayPhrase(serbianPhrase: string, lang: PhraseLanguage): string[] {{
  const srForms = formsOf("sr");
  return serbianPhrase.split("-").map((word) => {{
    const index = srForms.get(fold(word));
    return (index === undefined ? undefined : WORDS[lang][index]) ?? word;
  }});
}}
"""


class Command(BaseCommand):
    help = "Regenerate frontend/src/foodWords.ts from the phrase word lists."

    def handle(self, *args, **options) -> None:
        FRONTEND_FILE.write_text(render_frontend_module())
        self.stdout.write(self.style.SUCCESS(f"Wrote {FRONTEND_FILE}"))
