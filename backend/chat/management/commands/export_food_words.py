"""
Write frontend/src/foodWords.ts from chat/words.py.

The cover site needs the same words and case forms as the server: it only
sends a search to /api/chat/resume when all four words are recognized. This
command is the one place that file comes from, and a test fails when the
committed file is out of date.

    uv run python manage.py export_food_words
"""

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from chat.words import CASE_ENDINGS, FILLER_WORDS, FOOD_WORDS, word_stems

FRONTEND_FILE = Path(settings.BASE_DIR).parent / "frontend" / "src" / "foodWords.ts"


def render_frontend_module() -> str:
    stems = {word: list(word_stems(word)) for word in FOOD_WORDS}
    return f"""// GENERATED by `uv run python manage.py export_food_words` (backend).
// Source of truth: backend/chat/words.py. Do not edit by hand; a backend
// test fails if this file is out of date.
//
// The 105 resume-phrase words plus their case forms ("jaja" -> "jaje").
// Not secret: the strength comes from 105^4 phrases plus rate limits.

const CASE_ENDINGS: readonly string[] = {json.dumps(list(CASE_ENDINGS))};

/** Small words skipped between list words ("krofne, kore i maslaca"). */
export const FILLER_WORDS: ReadonlySet<string> = new Set({json.dumps(sorted(FILLER_WORDS))});

const STEMS: Readonly<Record<string, readonly string[]>> = {json.dumps(stems, indent=2)};

function buildForms(): Map<string, string> {{
  const forms = new Map<string, string>();
  for (const word of Object.keys(STEMS)) forms.set(word, word);
  for (const [word, stems] of Object.entries(STEMS)) {{
    for (const stem of stems) {{
      for (const ending of CASE_ENDINGS) {{
        if (!forms.has(stem + ending)) forms.set(stem + ending, word);
      }}
    }}
  }}
  return forms;
}}

/** Every accepted form (the word itself included) mapped to its list word. */
export const FOOD_FORMS: ReadonlyMap<string, string> = buildForms();
"""


class Command(BaseCommand):
    help = "Regenerate frontend/src/foodWords.ts from chat/words.py."

    def handle(self, *args, **options) -> None:
        FRONTEND_FILE.write_text(render_frontend_module())
        self.stdout.write(self.style.SUCCESS(f"Wrote {FRONTEND_FILE}"))
